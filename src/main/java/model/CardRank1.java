package model;

public class CardRank1 {
    private int id;
    private String ten;
    private int diemtoithieu;
    private float tilegiamgia;

    public CardRank1() {
        super();
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getTen() {
        return ten;
    }

    public void setTen(String ten) {
        this.ten = ten;
    }

    public int getDiemtoithieu() {
        return diemtoithieu;
    }

    public void setDiemtoithieu(int diemtoithieu) {
        this.diemtoithieu = diemtoithieu;
    }

    public float getTilegiamgia() {
        return tilegiamgia;
    }

    public void setTilegiamgia(float tilegiamgia) {
        this.tilegiamgia = tilegiamgia;
    }
}
